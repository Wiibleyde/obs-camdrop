#pragma once

#include <string>

namespace camdrop {

// Global plugin settings, stored as JSON in the plugin config directory
// (obs_module_config_path), never inside the OBS profile.
struct Settings {
	bool server_enabled = false; // disabled until the user turns it on
	int port = 7443;             // TCP: HTTPS page + WebSocket signaling
	int udp_port_min = 51000;    // UDP range for WebRTC media
	int udp_port_max = 51100;

	bool custom_cert = false; // false: self-signed certificate generated by the plugin
	std::string cert_path;    // PEM certificate (full chain) when custom_cert
	std::string key_path;     // PEM private key when custom_cert

	std::string access_code; // random code required by the web page and the dock

	int max_clients = 8;
	int video_height = 720;               // requested capture height (480 / 720 / 1080)
	int video_fps = 30;                   // 30 by default, 60 if the camera allows it
	int max_bitrate_kbps = 5000;          // per client
	std::string preferred_codec = "h264"; // "h264", "h265" or "vp8"
	bool hw_decode = true;                // D3D11VA / VideoToolbox / VAAPI, software fallback
	bool opus_10ms = false;               // ask browsers for 10 ms Opus frames
	std::string orientation = "any";      // "any", "landscape" or "portrait": hint shown on the phones

	bool tally = true;            // red/green border on the phones when their source is in program/preview
	bool auto_add_sources = true; // add a source to the current scene when a new camera joins

	bool operator==(const Settings &o) const = default;
};

Settings load_settings();
bool save_settings(const Settings &settings);
std::string generate_access_code();

// Absolute path inside the plugin config directory (created on demand).
std::string config_file_path(const char *name);

} // namespace camdrop
