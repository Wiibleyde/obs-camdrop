const camdropLang = (() => {
	const param = new URLSearchParams(location.search).get('lang');
	const candidates = [param, ...(navigator.languages || [navigator.language])].filter(Boolean);
	for (const c of candidates) {
		const short = String(c).toLowerCase().slice(0, 2);
		if (CAMDROP_STRINGS[short]) return short;
	}
	return 'en';
})();

function t(key, vars) {
	let s = (CAMDROP_STRINGS[camdropLang] && CAMDROP_STRINGS[camdropLang][key]) ?? CAMDROP_STRINGS.en[key] ?? key;
	if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
	return s;
}

function applyTranslations(root = document) {
	document.documentElement.lang = camdropLang;
	root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
	root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
	root.querySelectorAll('[data-i18n-title]').forEach((el) => {
		el.title = t(el.dataset.i18nTitle);
		el.setAttribute('aria-label', el.title);
	});
}
